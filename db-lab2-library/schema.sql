BEGIN;
CREATE TABLE author (
    author_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (author_id > 0),
    given_name text CHECK (given_name IS NULL OR btrim(given_name) <> ''),
    family_name text CHECK (family_name IS NULL OR btrim(family_name) <> ''),
    pen_name text CHECK (pen_name IS NULL OR btrim(pen_name) <> ''),
    CONSTRAINT author_has_name CHECK (coalesce(given_name, family_name, pen_name) IS NOT NULL)
);
CREATE TABLE edition (
    edition_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (edition_id > 0),
    title text NOT NULL CHECK (btrim(title) <> ''),
    language text NOT NULL CHECK (btrim(language) <> ''),
    publication_year integer CHECK (publication_year > 0),
    publisher_name text CHECK (publisher_name IS NULL OR btrim(publisher_name) <> '')
);
CREATE TABLE authorship (
    author_id integer NOT NULL REFERENCES author ON DELETE RESTRICT,
    edition_id integer NOT NULL REFERENCES edition ON DELETE RESTRICT,
    PRIMARY KEY (author_id, edition_id)
);
CREATE TABLE copy (
    inventory_number integer PRIMARY KEY CHECK (inventory_number > 0),
    edition_id integer NOT NULL REFERENCES edition ON DELETE RESTRICT
);
CREATE TABLE reader (
    reader_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (reader_id > 0),
    given_name text NOT NULL CHECK (btrim(given_name) <> ''),
    family_name text NOT NULL CHECK (btrim(family_name) <> ''),
    phone text NOT NULL CHECK (btrim(phone) <> '')
);
CREATE TABLE loan (
    loan_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (loan_id > 0),
    reader_id integer NOT NULL REFERENCES reader ON DELETE RESTRICT,
    inventory_number integer NOT NULL REFERENCES copy ON DELETE RESTRICT,
    issued_on date NOT NULL,
    due_on date NOT NULL,
    returned_on date,
    CONSTRAINT loan_due_date CHECK (due_on >= issued_on),
    CONSTRAINT loan_return_date CHECK (returned_on >= issued_on)
);
CREATE UNIQUE INDEX loan_one_open_copy ON loan (inventory_number) WHERE returned_on IS NULL;
CREATE INDEX loan_reader_idx ON loan (reader_id);
CREATE INDEX copy_edition_idx ON copy (edition_id);
CREATE INDEX authorship_edition_idx ON authorship (edition_id);

CREATE FUNCTION guard_loan_period() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.inventory_number <> OLD.inventory_number THEN
        RAISE EXCEPTION 'Move a loan to another copy by correcting the source transaction' USING ERRCODE = '23514';
    END IF;
    UPDATE copy SET edition_id = edition_id WHERE inventory_number = NEW.inventory_number;
    IF EXISTS (
        SELECT 1 FROM loan l
        WHERE l.inventory_number = NEW.inventory_number AND l.loan_id <> NEW.loan_id
          AND NEW.issued_on < coalesce(l.returned_on, 'infinity'::date)
          AND l.issued_on < coalesce(NEW.returned_on, 'infinity'::date)
    ) THEN
        RAISE EXCEPTION 'Loan periods overlap for copy %', NEW.inventory_number USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER loan_period_guard BEFORE INSERT OR UPDATE ON loan
FOR EACH ROW EXECUTE FUNCTION guard_loan_period();

CREATE FUNCTION check_catalog_minimum() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM edition e WHERE NOT EXISTS
        (SELECT 1 FROM copy c WHERE c.edition_id = e.edition_id)) THEN
        RAISE EXCEPTION 'Every edition needs at least one copy' USING ERRCODE = '23514';
    END IF;
    IF EXISTS (SELECT 1 FROM author a WHERE NOT EXISTS
        (SELECT 1 FROM authorship s WHERE s.author_id = a.author_id)) THEN
        RAISE EXCEPTION 'Every author needs at least one edition' USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER edition_minimum AFTER INSERT OR UPDATE OR DELETE ON edition
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_catalog_minimum();
CREATE CONSTRAINT TRIGGER copy_minimum AFTER INSERT OR UPDATE OR DELETE ON copy
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_catalog_minimum();
CREATE CONSTRAINT TRIGGER author_minimum AFTER INSERT OR UPDATE OR DELETE ON author
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_catalog_minimum();
CREATE CONSTRAINT TRIGGER authorship_minimum AFTER INSERT OR UPDATE OR DELETE ON authorship
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_catalog_minimum();

CREATE FUNCTION lock_catalog_parent() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME = 'copy' THEN
        IF TG_OP <> 'INSERT' THEN
            UPDATE edition SET title = title WHERE edition_id = OLD.edition_id;
        END IF;
        IF TG_OP <> 'DELETE' THEN
            UPDATE edition SET title = title WHERE edition_id = NEW.edition_id;
        END IF;
    ELSE
        IF TG_OP <> 'INSERT' THEN
            UPDATE author SET author_id = author_id WHERE author_id = OLD.author_id;
        END IF;
        IF TG_OP <> 'DELETE' THEN
            UPDATE author SET author_id = author_id WHERE author_id = NEW.author_id;
        END IF;
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER copy_parent_lock BEFORE INSERT OR UPDATE OF edition_id OR DELETE ON copy
FOR EACH ROW EXECUTE FUNCTION lock_catalog_parent();
CREATE TRIGGER authorship_parent_lock BEFORE INSERT OR UPDATE OR DELETE ON authorship
FOR EACH ROW EXECUTE FUNCTION lock_catalog_parent();
COMMIT;
